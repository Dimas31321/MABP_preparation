export function registerExtraQuestions(bank) {
  for (const question of extraBank) {
    const existing = bank.find((item) => item.id === question.id);
    if (existing && JSON.stringify(existing) !== JSON.stringify(question)) {
      throw new Error(`Конфликт ID дополнительного задания: ${question.id}`);
    }
    if (!existing) bank.push(question);
  }
}

// Добавляет раздел только на главную страницу. Не требует изменений HTML и CSS.
export function installAdditionalPractice({ bank, start, getAttempts }) {
  const app = document.querySelector("#app");
  if (!app) throw new Error("Не найден контейнер #app");

  function mount() {
    const oldCards = app.querySelector(".cards");
    if (!oldCards || app.querySelector("#additional-practice")) return;
    const section = document.createElement("section");
    section.id = "additional-practice";
    section.setAttribute("aria-labelledby", "additional-practice-title");
    section.style.marginTop = "48px";
    const attempts = getAttempts();
    section.innerHTML = `
      <div class="sectionbar">
        <h2 id="additional-practice-title">Дополнительная практика</h2>
        <span class="pill">4 новых варианта · 60 заданий</span>
      </div>
      <p class="small">Авторские задания по темам курса. Выбранный режим «Тренировка» или «Экзамен» действует и здесь.</p>
      <div class="cards" style="grid-template-columns: repeat(auto-fit, minmax(min(100%, 420px), 1fr))">
        ${extraVariants
          .map((variant, i) => {
            const last = attempts.filter((a) => a.v === variant.v).at(-1);
            const total = bank.filter(
              (q) => q.v === variant.v && !q.open,
            ).length;
            return `
            <article class="card">
              <div class="card-top">
                <span class="num">ДОПОЛНИТЕЛЬНЫЙ 0${i + 1}</span>
                <span class="pill">Новая практика</span>
              </div>
              <h3>${variant.title}</h3>
              <p>${variant.description}</p>
              <div class="tags">${variant.tags.map((tag) => `<span>${tag}</span>`).join("")}</div>
              <div class="card-bottom">
                <div class="meta">
                  <span>${total} тестов + 3 кейса</span>
                  <span>${last ? `Последний: ${last.correct}/${last.total ?? total}` : "Ещё не пройден"}</span>
                </div>
                <button class="primary" data-extra-start="${variant.v}">
                  <span>Начать вариант</span><span>↗</span>
                </button>
              </div>
            </article>`;
          })
          .join("")}
      </div>`;
    oldCards.after(section);
    section.querySelectorAll("[data-extra-start]").forEach((button) => {
      button.addEventListener("click", () =>
        start(Number(button.dataset.extraStart)),
      );
    });
  }

  const observer = new MutationObserver(mount);
  observer.observe(app, { childList: true });
  mount();
  return () => observer.disconnect();
}
